import { join } from "node:path";
import { COUNTRY_CODES } from "../../../src/location/value-objects/country-code.ts";
import { keptTemplate, keptUppercase } from "./address-template.ts";

const LIBADDRESSINPUT_COMMIT = "81eb9628382b07d371d8ea0b11badf7de3857fd5";
const COUNTRY_INFO_URL = `https://raw.githubusercontent.com/google/libaddressinput/${LIBADDRESSINPUT_COMMIT}/testdata/countryinfo.txt`;
const ISO_CODES_URL = "https://unpkg.com/i18n-iso-countries@7.14.0/codes.json";

const countryCodes = new Set<string>(COUNTRY_CODES);

const outputDirectory = join(
	import.meta.dir,
	"../../../src/location/lib/generated",
);

interface RegionData {
	readonly key?: string;
	readonly fmt?: string;
	readonly lfmt?: string;
	readonly upper?: string;
}

async function download(url: string) {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url}: ${response.status}`);
	return response.text();
}

function countryRegions(countryInfo: string): Array<RegionData> {
	return countryInfo
		.split("\n")
		.filter((line) => /^data\/[A-Z]{2}=/u.test(line))
		.map((line) => JSON.parse(line.slice(line.indexOf("=") + 1)) as RegionData);
}

function formatEntry(region: RegionData): string | null {
	if (region.key === undefined || region.fmt === undefined) return null;
	if (!countryCodes.has(region.key)) return null;
	const fields = [`template: ${JSON.stringify(keptTemplate(region.fmt))}`];
	if (region.lfmt !== undefined) {
		fields.push(`latinTemplate: ${JSON.stringify(keptTemplate(region.lfmt))}`);
	}
	const uppercase = keptUppercase(region.upper);
	if (uppercase !== undefined) {
		fields.push(`uppercase: ${JSON.stringify(uppercase)}`);
	}
	return `${region.key}: { ${fields.join(", ")} },`;
}

async function writeAddressFormats() {
	const regions = countryRegions(await download(COUNTRY_INFO_URL));
	const entries = regions.flatMap((region) => formatEntry(region) ?? []);
	await Bun.write(
		join(outputDirectory, "address-format-data.ts"),
		`// Generated by scripts/country-data from Google libaddressinput (Apache-2.0), commit ${LIBADDRESSINPUT_COMMIT}.
import type { AddressFormat } from "#location/lib/address-format";
import type { CountryCode } from "#location/value-objects/country-code";

export const ADDRESS_FORMAT_DATA: Partial<Record<CountryCode, AddressFormat>> = {
${entries.join("\n")}
};
`,
	);
}

async function writeAlpha3Codes() {
	const codes = JSON.parse(await download(ISO_CODES_URL)) as Array<
		[string, string, ...Array<string>]
	>;
	const entries = codes
		.filter(([alpha2]) => countryCodes.has(alpha2))
		.map(([alpha2, alpha3]) => `${alpha2}: "${alpha3}",`)
		.sort();
	await Bun.write(
		join(outputDirectory, "alpha3-data.ts"),
		`// Generated by scripts/country-data from i18n-iso-countries (MIT).
import type { CountryCode } from "#location/value-objects/country-code";

export const ALPHA3_DATA: Record<CountryCode, string> = {
${entries.join("\n")}
};
`,
	);
}

await Promise.all([writeAddressFormats(), writeAlpha3Codes()]);
